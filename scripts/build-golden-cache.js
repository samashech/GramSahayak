#!/usr/bin/env node
// Builds backend/cache/golden-cache.json (B-10) from the REAL RAG service, so the demo still
// answers the golden queries when RAG/Groq/Wi-Fi are down. Every row in data/seed/golden_queries.json
// is asked in all its languages, for chat and voice. A row whose matched scheme differs from the
// appendix expectation is NOT cached (the build fails), so the cache never stores a wrong answer.
// Only answer text + scheme id are cached; SMS receipts always come from data/seed (R5).
//
//   node scripts/build-golden-cache.js [RAG_URL]      (default http://127.0.0.1:8000)

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const RAG_URL = (process.argv[2] || process.env.AI_RAG_URL || 'http://127.0.0.1:8000').replace(/\/+$/, '');
const OUT = path.join(ROOT, 'backend', 'cache', 'golden-cache.json');
const { queries } = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'seed', 'golden_queries.json'), 'utf8'));
const { normalizeQuery } = require(path.join(ROOT, 'backend', 'src', 'services', 'demoCache.js'));

async function ask(query, language, row, forVoice) {
  const res = await fetch(`${RAG_URL}/rag/query`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ query, language, category: row.category, role: row.role, for_voice: forVoice, history: [] }),
    signal: AbortSignal.timeout(15000),
  });
  if (!res.ok) throw new Error(`${row.id} ${language}: HTTP ${res.status}`);
  return res.json();
}

(async () => {
  const health = await (await fetch(`${RAG_URL}/health`)).json();
  console.log(`RAG ${RAG_URL}: status=${health.status} vectors=${health.vector_count} mode=${health.mode}`);
  const entries = {};
  const problems = [];
  for (const row of queries) {
    for (const [language, text] of Object.entries(row.text)) {
      const [chat, voice] = [await ask(text, language, row, false), await ask(text, language, row, true)];
      if ((chat.matched_scheme_id ?? null) !== row.expect.matched) {
        problems.push(`${row.id} ${language}: matched ${chat.matched_scheme_id} != expected ${row.expect.matched}`);
        continue;
      }
      entries[`${language}|${normalizeQuery(text)}`] = {
        id: row.id,
        languageCode: language,
        category: row.category,
        matchedSchemeId: chat.matched_scheme_id ?? null,
        answerText: { chat: chat.answer, voice: voice.answer },
        sources: (chat.sources || []).map((s) => ({ id: s.id, title: s.title, category: s.category, helpline: s.helpline, portalUrl: s.portal })),
        ragMode: chat.mode,
      };
      console.log(`  ${row.id} ${language}  matched=${chat.matched_scheme_id ?? '-'}  mode=${chat.mode}`);
    }
  }
  if (problems.length) {
    console.error(`\nNOT cached (${problems.length}):\n  ${problems.join('\n  ')}`);
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `${JSON.stringify({
    _note: 'Generated by scripts/build-golden-cache.js from the live RAG service. Do not edit by hand. SMS receipts are NOT stored here; they come from data/seed/schemes.json at runtime (R5).',
    generatedAt: new Date().toISOString(),
    rag: { url: RAG_URL, mode: health.mode, vectors: health.vector_count },
    entries,
  }, null, 2)}\n`);
  console.log(`\nWrote ${Object.keys(entries).length} entries -> ${path.relative(ROOT, OUT)}`);
  process.exit(problems.length ? 1 : 0);
})().catch((err) => { console.error(err.message); process.exit(1); });
